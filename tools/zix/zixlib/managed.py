"""The zix-managed package set and pin registry.

``zix/managed/manifest.json`` is the source of truth:

    {
      "version": 1,
      "packages": [ {"name": "foo", "target": "managed", "added": "..."} ],
      "pins":     { "jq": {"version": "1.7.1", "added": "..."} }
    }

Two files are generated from it on every change:

* ``zix/managed/packages.nix`` - the package list imported by
  ``modules/shared/packages.nix`` (so managed entries reach every host).
* ``zix/managed/pins.json`` - read directly by the pin overlay in
  ``lib/nixpkgs.nix`` (via ``inputs.multiverse.lib.pinOverlay``).
"""

import json

from .util import ZixError, iso_date


class Managed:
    def __init__(self, cfg, ui):
        self.cfg = cfg
        self.ui = ui
        self.path = cfg.manifest_path
        self.data = self._load()

    def _load(self):
        if self.path.exists():
            try:
                data = json.loads(self.path.read_text())
            except json.JSONDecodeError as exc:
                raise ZixError("%s is not valid JSON: %s" % (self.path, exc))
        else:
            data = {}
        data.setdefault("version", 1)
        data.setdefault("packages", [])
        data.setdefault("pins", {})
        return data

    # -- queries -------------------------------------------------------------

    @property
    def packages(self):
        return self.data["packages"]

    @property
    def pins(self):
        return self.data["pins"]

    def has_package(self, name):
        return any(p["name"] == name for p in self.packages)

    def has_pin(self, name):
        return name in self.pins

    # -- mutations -----------------------------------------------------------

    def add_package(self, name, target):
        if self.has_package(name):
            return False
        self.data["packages"].append(
            {"name": name, "target": target, "added": iso_date()})
        return True

    def remove_package(self, name):
        before = len(self.packages)
        self.data["packages"] = [p for p in self.packages
                                 if p["name"] != name]
        return before - len(self.data["packages"])

    def set_pin(self, name, version):
        self.data["pins"][name] = {"version": version, "added": iso_date()}

    def remove_pin(self, name):
        return self.data["pins"].pop(name, None)

    # -- generation ----------------------------------------------------------

    def rendered(self):
        """Every generated file's intended content, keyed by path."""
        return {
            self.path: json.dumps(self._sorted_payload(), indent=2,
                                  sort_keys=True) + "\n",
            self.cfg.packages_file: self._packages_nix_text(),
            self.cfg.pins_file: self._pins_json_text(),
        }

    def save(self):
        """Write manifest + regenerated packages.nix and pins.json."""
        for path, text in self.rendered().items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)

    def _sorted_payload(self):
        data = {
            "version": 1,
            "packages": sorted(self.packages, key=lambda p: p["name"]),
            "pins": {name: self.pins[name] for name in sorted(self.pins)},
        }
        return data

    def _packages_nix_text(self):
        names = sorted({p["name"] for p in self.packages})
        body = "".join("  %s\n" % name for name in names)
        return (
            "# Generated by zix from zix/managed/manifest.json - do not edit by hand.\n"
            "# Add or remove entries with:\n"
            "#   nix run .#zix -- pkg add NAME      (target: managed = every host)\n"
            "#   nix run .#zix -- pkg rm NAME\n"
            "{ pkgs }:\n"
            "with pkgs;\n"
            "[\n"
            "%s"
            "]\n" % body
        )

    def _pins_json_text(self):
        pins = {name: self.pins[name]["version"] for name in sorted(self.pins)}
        return json.dumps(pins, indent=2, sort_keys=True) + "\n"
