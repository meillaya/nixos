# Stubs are Python scripts run through the interpreter executing the tests, so
# they work inside a Nix build sandbox too (no /bin/sh, no /usr/bin/env).
NIX_STUB_BODY = """import os
import sys

argv = sys.argv[1:]
if argv and argv[0] == "--version":
    print("nix (Nix) 2.99.0-test")
    sys.exit(0)
if argv and argv[0] == "--parse":
    sys.exit(0 if len(argv) > 1 and os.path.exists(argv[1]) else 1)
if argv and argv[0] == "eval":
    sys.stdout.write(os.environ.get("FAKE_NIX_EVAL_OUTPUT", "2.0.0"))
    sys.exit(0)
sys.exit(0)
"""

MVS_STUB_BODY = """import json
import sys

if "--json" in sys.argv:
    print(json.dumps({"attr": sys.argv[-1],
                      "versions": [{"version": "1.0.0"},
                                   {"version": "2.0.0"}]}))
else:
    print("some-attr \\\\u00b7 2 versions \\\\u00b7 2019-01-01 .. 2025-01-01")
    print("VERSION  FIRST       LAST        REVS")
    print("1.0.0    2019-01-01  2019-01-01  1")
    print("2.0.0    2024-01-01  2025-01-01  3")
"""


def stub(body):
    return "#!%s\n%s" % (sys.executable, body)


def _write_executable(path, text):
    path.write_text(text)
    path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP)


def tree_snapshot(root):
    """Every file under root as {relative path: text} for change detection.

    ``zix/backups/`` is skipped: snapshots are kept on purpose (including
    after a rollback), so they are not "changes".
    """
    snapshot = {}
    for path in sorted(Path(root).rglob("*")):
        if not path.is_file():
            continue
        rel = str(path.relative_to(root))
        if rel.startswith("zix/backups/"):
            continue
        snapshot[rel] = path.read_text()
    return snapshot


class FixtureRepo:
    def __init__(self, base):
        base = Path(base)
        self.root = base / "repo"
        self.bin = base / "bin"
        for directory in ("modules/shared", "modules/linux", "zix/managed"):
            (self.root / directory).mkdir(parents=True, exist_ok=True)
        self.bin.mkdir(parents=True, exist_ok=True)
        for name in ("nix", "nix-instantiate"):
            _write_executable(self.bin / name, stub(NIX_STUB_BODY))
        self.fake_mvs = self.bin / "fake-mvs"
        _write_executable(self.fake_mvs, stub(MVS_STUB_BODY))
        self._write_repo_files()

    def _write_repo_files(self):
        (self.root / "flake.nix").write_text(
            '{\n'
            '  description = "fixture";\n'
            '  inputs = {\n'
            '    nixpkgs.url = "github:nixos/nixpkgs/nixos-unstable";\n'
            '  };\n'
            '  outputs = inputs: { };\n'
            '}\n')
        (self.root / "modules/shared/packages.nix").write_text(
            "{ pkgs }:\nwith pkgs;\n[\n  existing-shared\n]\n")
        (self.root / "modules/linux/packages.nix").write_text(
            "{ pkgs, ... }:\nwith pkgs;\n[\n  existing-linux\n]\n")
        (self.root / "zix/managed/packages.nix").write_text(
            "# Generated by zix from zix/managed/manifest.json\n"
            "{ pkgs }:\nwith pkgs;\n[\n]\n")
        (self.root / "zix/managed/pins.json").write_text("{}\n")
        (self.root / "zix/managed/manifest.json").write_text(
            json.dumps({"version": 1, "packages": [], "pins": {}},
                       indent=2, sort_keys=True) + "\n")
        (self.root / "zix.json").write_text(
            json.dumps(self._config(), indent=2, sort_keys=True) + "\n")

    def _config(self):
        return {
            "version": 1,
            "name": "fixture-repo",
            "system": "x86_64-linux",
            "targets": {
                "managed": {"kind": "managed"},
                "shared": {"kind": "list",
                           "file": "modules/shared/packages.nix"},
                "linux": {"kind": "list",
                          "file": "modules/linux/packages.nix"},
            },
            "managed": {
                "manifest": "zix/managed/manifest.json",
                "packages_file": "zix/managed/packages.nix",
                "pins_file": "zix/managed/pins.json",
            },
            "tools": {
                "multiverse": {"command": [str(self.fake_mvs)]},
                "auto_follow": {"command": [str(self.fake_mvs)]},
            },
            "switches": {"fixture-host": [str(self.fake_mvs)]},
            "default_switch": "fixture-host",
            "update_command": [str(self.fake_mvs)],
        }

    def env(self, **extra):
        env = dict(os.environ)
        env["PATH"] = "%s%s%s" % (self.bin, os.pathsep, env.get("PATH", ""))
        env.pop("ZIX_REPO", None)
        env.update(extra)
        return env

    def cli(self, *args, **kwargs):
        env = self.env(**(kwargs.pop("env", None) or {}))
        cwd = kwargs.pop("cwd", None)
        expect = kwargs.pop("expect", 0)
        proc = subprocess.run(
            [sys.executable, str(ZIX_DIR / "cli.py"),
             "--repo", str(self.root)] + list(args),
            capture_output=True, text=True, env=env,
            cwd=str(cwd or self.root))
        if expect is not None:
            self.assert_return(proc, expect)
        return proc

    def assert_return(self, proc, expect):
        if proc.returncode != expect:
            raise AssertionError(
                "expected exit %s, got %s\nstdout:\n%s\nstderr:\n%s"
                % (expect, proc.returncode, proc.stdout, proc.stderr))

    def manifest(self):
        return json.loads((self.root / "zix/managed/manifest.json").read_text())

    def pins(self):
        return json.loads((self.root / "zix/managed/pins.json").read_text())


class NixeditTests(unittest.TestCase):
    LIST = "{ pkgs }:\nwith pkgs;\n[\n  htop\n]\n"

    def test_insert_creates_markers_and_is_idempotent(self):
        text, added = nixedit.insert_token(self.LIST, "cowsay")
        self.assertTrue(added)
        self.assertIn(nixedit.MARK_BEGIN, text)
        self.assertIn("  cowsay\n", text)
        again, added_again = nixedit.insert_token(text, "cowsay")
        self.assertFalse(added_again)
        self.assertEqual(text, again)

    def test_remove_only_matches_whole_lines(self):
        text = "{ pkgs }:\nwith pkgs;\n[\n  htop\n  htopx\n  pkgs.htop\n]\n"
        new, count = nixedit.remove_token(text, "htop")
        self.assertEqual(count, 2)
        self.assertIn("htopx", new)
        self.assertNotIn("\n  htop\n", new)

    def test_input_round_trip(self):
        flake = ('{\n  inputs = {\n'
                 '    nixpkgs.url = "github:nixos/nixpkgs/nixos-unstable";\n'
                 '  };\n  outputs = x: { };\n}\n')
        text, added = nixedit.add_input(
            flake, "disko", "github:nix-community/disko",
            {"nixpkgs": "nixpkgs"})
        self.assertTrue(added)
        self.assertIn('disko.url = "github:nix-community/disko";', text)
        self.assertIn('disko.inputs.nixpkgs.follows = "nixpkgs";', text)
        self.assertEqual(nixedit.input_url(text, "disko"),
                         "github:nix-community/disko")
        again, added_again = nixedit.add_input(text, "disko", "x")
        self.assertFalse(added_again)
        self.assertEqual(text, again)
        removed, count = nixedit.remove_input(text, "disko")
        self.assertEqual(count, 2)
        self.assertNotIn("disko", removed)

    def test_block_input_refused(self):
        text = ('{\n  inputs = {\n    foo = {\n'
                '      url = "github:me/foo";\n    };\n'
                '  };\n  outputs = x: { };\n}\n')
        with self.assertRaises(ZixError):
            nixedit.remove_input(text, "foo")

    def test_input_reads_block_style(self):
        flake = ('{\n  inputs = {\n'
                 '    emacs-overlay = {\n'
                 '      url = "github:dustinlyons/emacs-overlay";\n'
                 '      flake = false;\n'
                 '    };\n'
                 '    nixpkgs.url = "github:nixos/nixpkgs/nixos-unstable";\n'
                 '  };\n  outputs = x: { };\n}\n')
        self.assertEqual(nixedit.input_names(flake),
                         ["emacs-overlay", "nixpkgs"])
        self.assertEqual(nixedit.input_url(flake, "emacs-overlay"),
                         "github:dustinlyons/emacs-overlay")
        self.assertEqual(nixedit.input_url(flake, "nixpkgs"),
                         "github:nixos/nixpkgs/nixos-unstable")
        self.assertIsNone(nixedit.input_url(flake, "missing"))


class ManagedTests(unittest.TestCase):
    def test_rendered_matches_manifest(self):
        with tempfile.TemporaryDirectory() as tmp:
            fixture = FixtureRepo(tmp)
            cfg = load_config(fixture.root)
            managed = Managed(cfg, UI(color=False, quiet=True))
            managed.add_package("cowsay", "managed")
            managed.set_pin("jq", "2.0.0")
            rendered = managed.rendered()
            self.assertEqual(json.loads(rendered[cfg.pins_file]),
                             {"jq": "2.0.0"})
            self.assertIn("  cowsay\n", rendered[cfg.packages_file])
            payload = json.loads(rendered[cfg.manifest_path])
            self.assertEqual(payload["pins"]["jq"]["version"], "2.0.0")


