class CliTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.fixture = FixtureRepo(self.tmp.name)

    def tearDown(self):
        self.tmp.cleanup()

    def test_add_rm_cycle_is_idempotent(self):
        fixture = self.fixture
        proc = fixture.cli("pkg", "add", "cowsay")
        self.assertIn("cowsay", proc.stdout)
        self.assertEqual([p["name"] for p in fixture.manifest()["packages"]],
                         ["cowsay"])
        self.assertIn("  cowsay\n",
                      (fixture.root / "zix/managed/packages.nix").read_text())
        again = fixture.cli("pkg", "add", "cowsay")
        self.assertIn("already declared", again.stdout)
        self.assertIn("managed", fixture.cli("pkg", "where", "cowsay").stdout)
        fixture.cli("pkg", "rm", "cowsay")
        self.assertEqual(fixture.manifest()["packages"], [])
        self.assertNotIn("cowsay",
                         (fixture.root / "zix/managed/packages.nix").read_text())
        missing = fixture.cli("pkg", "rm", "cowsay")
        self.assertIn("nothing to remove", missing.stdout)

    def test_add_to_curated_list(self):
        fixture = self.fixture
        fixture.cli("pkg", "add", "kitty", "--target", "linux")
        path = fixture.root / "modules/linux/packages.nix"
        text = path.read_text()
        self.assertIn(nixedit.MARK_BEGIN, text)
        self.assertIn("  kitty\n", text)
        fixture.cli("pkg", "add", "kitty", "--target", "linux")
        self.assertEqual(text, path.read_text())
        fixture.cli("pkg", "rm", "kitty")
        self.assertNotIn("  kitty\n", path.read_text())
        self.assertIn(nixedit.MARK_BEGIN, path.read_text())

    def test_dry_run_pin_changes_nothing(self):
        fixture = self.fixture
        before = tree_snapshot(fixture.root)
        proc = fixture.cli("--dry-run", "pkg", "add", "jq@2.0.0")
        self.assertIn("2.0.0", proc.stdout)
        self.assertEqual(before, tree_snapshot(fixture.root))

    def test_pin_writes_input_pin_and_declaration(self):
        fixture = self.fixture
        fixture.cli("pkg", "add", "jq@2.0.0",
                    env={"FAKE_NIX_EVAL_OUTPUT": "2.0.0"})
        self.assertIn("multiverse",
                      (fixture.root / "flake.nix").read_text())
        self.assertEqual(fixture.pins(), {"jq": "2.0.0"})
        self.assertEqual(fixture.manifest()["pins"]["jq"]["version"], "2.0.0")
        self.assertIn("  jq\n",
                      (fixture.root / "zix/managed/packages.nix").read_text())

    def test_pin_mismatch_rolls_back(self):
        fixture = self.fixture
        before = tree_snapshot(fixture.root)
        proc = fixture.cli("pkg", "add", "jq@2.0.0",
                           env={"FAKE_NIX_EVAL_OUTPUT": "9.9.9"},
                           expect=None)
        self.assertNotEqual(proc.returncode, 0)
        self.assertIn("rolled back", proc.stdout + proc.stderr)
        self.assertEqual(before, tree_snapshot(fixture.root))

    def test_pin_unknown_version_refused(self):
        fixture = self.fixture
        before = tree_snapshot(fixture.root)
        proc = fixture.cli("pkg", "add", "jq@9.9.9", expect=None)
        self.assertNotEqual(proc.returncode, 0)
        self.assertIn("never shipped", proc.stdout + proc.stderr)
        self.assertEqual(before, tree_snapshot(fixture.root))

    def test_unpin(self):
        fixture = self.fixture
        fixture.cli("pkg", "add", "jq@2.0.0",
                    env={"FAKE_NIX_EVAL_OUTPUT": "2.0.0"})
        fixture.cli("pkg", "unpin", "jq")
        self.assertEqual(fixture.pins(), {})
        self.assertIn("not pinned", fixture.cli("pkg", "unpin", "jq").stdout)

    def test_follows_check_uses_tool(self):
        proc = self.fixture.cli("follows", "check")
        self.assertEqual(proc.returncode, 0)

    def test_switch_passes_dash_args_to_the_app(self):
        proc = self.fixture.cli("switch", "--", "--dry-run")
        self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)

    def test_repo_discovery_from_subdirectory(self):
        fixture = self.fixture
        proc = subprocess.run(
            [sys.executable, str(ZIX_DIR / "cli.py"), "pkg", "list"],
            capture_output=True, text=True, env=fixture.env(),
            cwd=str(fixture.root / "modules"))
        fixture.assert_return(proc, 0)

    def test_default_target_from_manifest(self):
        fixture = self.fixture
        config_path = fixture.root / "zix.json"
        config = json.loads(config_path.read_text())
        config["default_target"] = "shared"
        config_path.write_text(json.dumps(config, indent=2, sort_keys=True)
                               + "\n")
        fixture.cli("pkg", "add", "cowsay")
        self.assertIn("  cowsay\n",
                      (fixture.root / "modules/shared/packages.nix").read_text())
        self.assertEqual(fixture.manifest()["packages"], [])

    def test_no_pins_manifest_refuses_version_pins(self):
        fixture = self.fixture
        config_path = fixture.root / "zix.json"
        config = json.loads(config_path.read_text())
        config["no_pins"] = True
        config_path.write_text(json.dumps(config, indent=2, sort_keys=True)
                               + "\n")
        before = tree_snapshot(fixture.root)
        proc = fixture.cli("pkg", "add", "jq@2.0.0", expect=None)
        self.assertNotEqual(proc.returncode, 0)
        self.assertIn("no_pins", proc.stdout + proc.stderr)
        self.assertEqual(before, tree_snapshot(fixture.root))

    def test_where_sees_aspect_declarations(self):
        fixture = self.fixture
        path = fixture.root / "modules/aspects/users/mei.nix"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("{ pkgs, ... }: {\n  home.packages = [ pkgs.herdr ];\n}\n")
        proc = fixture.cli("pkg", "where", "herdr")
        self.assertIn("aspect", proc.stdout)
        self.assertIn("modules/aspects/users/mei.nix:2", proc.stdout)
        before = tree_snapshot(fixture.root)
        proc = fixture.cli("--dry-run", "pkg", "add", "herdr")
        self.assertIn("already declared", proc.stdout)
        self.assertEqual(before, tree_snapshot(fixture.root))

    def test_rm_refuses_aspect_declarations(self):
        fixture = self.fixture
        path = fixture.root / "modules/aspects/users/mei.nix"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("{ pkgs, ... }: {\n  home.packages = [ pkgs.herdr ];\n}\n")
        before = tree_snapshot(fixture.root)
        proc = fixture.cli("pkg", "rm", "herdr")
        self.assertIn("declared by hand", proc.stdout + proc.stderr)
        self.assertIn("only declared by hand", proc.stdout)
        self.assertEqual(before, tree_snapshot(fixture.root))

    def test_doctor_survives_minimal_environment(self):
        proc = self.fixture.cli("doctor", expect=None)
        self.assertIn(proc.returncode, (0, 1))
        self.assertIn("zix doctor", proc.stdout)


class GetTests(unittest.TestCase):
    """`zix get` is the runtime path: it must work with no repository."""

    def _run(self, tmp, *args):
        env = dict(os.environ)
        env.pop("ZIX_REPO", None)
        env["ZIX_SYSTEM_CONFIG"] = str(Path(tmp) / "no-system-config")
        return subprocess.run(
            [sys.executable, str(ZIX_DIR / "cli.py")] + list(args),
            capture_output=True, text=True, cwd=str(tmp), env=env)

    def test_get_dry_run_needs_no_repo(self):
        with tempfile.TemporaryDirectory() as tmp:
            proc = self._run(tmp, "--dry-run", "get", "hello@2.10")
            self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)
            self.assertIn('fast.versions.hello."2.10".out', proc.stdout)
            self.assertIn("nix profile add", proc.stdout)

    def test_get_eval_road_refs(self):
        with tempfile.TemporaryDirectory() as tmp:
            proc = self._run(tmp, "--dry-run", "get", "hello@2.10",
                             "--eval-road")
            self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)
            self.assertIn('versions.hello."2.10"', proc.stdout)
            self.assertNotIn("#fast", proc.stdout)
            proc = self._run(tmp, "--dry-run", "get", "hello", "--eval-road")
            self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)
            self.assertIn("nixpkgs#hello", proc.stdout)

    def test_get_without_specs_asks_for_one(self):
        with tempfile.TemporaryDirectory() as tmp:
            proc = self._run(tmp, "get")
            self.assertNotEqual(proc.returncode, 0)
            self.assertIn("nothing to get", proc.stdout + proc.stderr)

    def test_other_commands_still_need_a_repo(self):
        with tempfile.TemporaryDirectory() as tmp:
            proc = self._run(tmp, "pkg", "list")
            self.assertNotEqual(proc.returncode, 0)
            self.assertIn("no zix.json", proc.stdout + proc.stderr)


