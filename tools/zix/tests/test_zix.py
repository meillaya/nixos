"""Unit and fixture tests for the zix CLI. Offline: no network, no real nix.

Every nix binary zix calls is shadowed by a stub script in a temporary bin/
directory prepended to PATH, so the parse checks, flake locking and pin
verification code paths all run end to end without nix present.

Run from the repo root:
    python3 -m unittest discover -s tools/zix/tests -v
or through the repo check:
    bash tests/zix.sh
"""

